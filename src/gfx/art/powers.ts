const paths = new Map<PowerId, Path2D[]>();

export function drawPowerIcon(x: number, y: number, size: number, id: PowerId) {
  let print = paths.get(id);
  if (!print) {
    const [, ...cuts] = PRINTS[id];
    print = cuts.map((cut) => new Path2D(cut));
    paths.set(id, print);
  }
  const [body, planes, lines, accent] = print;
  const m = P[PRINTS[id][0]];
  const s = size / 112;

  g.save();
  g.translate(x + size / 2, y + size / 2);
  g.scale(s, s);
  g.translate(-60, -50);
  g.lineJoin = 'round';
  g.lineCap = 'round';
  g.fillStyle = m[1];
  g.fill(body);
  g.fillStyle = m[2];
  g.fill(planes);
  if (accent) {
    g.fillStyle = m[4];
    g.fill(accent);
  }
  g.strokeStyle = m[3];
  g.lineWidth = Math.max(1.5, 0.8 / s);
  g.stroke(body);
  // Keeping only the larger shapes at HUD size prevents the ink lines from merging.
  if (size >= 36) {
    g.lineWidth = 1;
    g.stroke(lines);
  }
  g.restore();
}
